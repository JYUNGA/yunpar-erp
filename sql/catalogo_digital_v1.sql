-- =========================================================
-- 1. FUNCIÓN GENERAL PARA updated_at
-- =========================================================

CREATE OR REPLACE FUNCTION public.catalogo_actualizar_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;


