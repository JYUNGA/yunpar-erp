-- =========================================================
-- 5. CONTROL AUTOMÁTICO DE PUBLICACIÓN
-- =========================================================

CREATE OR REPLACE FUNCTION
public.catalogo_controlar_publicacion()

RETURNS TRIGGER

LANGUAGE plpgsql

AS $$
BEGIN

    -- Si pasa a PUBLICADO,
    -- registra automáticamente la fecha.

    IF NEW.estado = 'PUBLICADO' THEN

        IF TG_OP = 'INSERT' THEN

            IF NEW.published_at IS NULL THEN
                NEW.published_at = NOW();
            END IF;

        ELSIF OLD.estado IS DISTINCT FROM 'PUBLICADO' THEN

            NEW.published_at = NOW();

        END IF;

    END IF;


    -- Si vuelve a BORRADOR,
    -- deja de considerarse publicado.

    IF NEW.estado = 'BORRADOR' THEN
        NEW.published_at = NULL;
    END IF;


    RETURN NEW;

END;
$$;


DROP TRIGGER IF EXISTS
trg_catalogo_controlar_publicacion
ON public.catalogo_disenos;


CREATE TRIGGER trg_catalogo_controlar_publicacion

BEFORE INSERT OR UPDATE
ON public.catalogo_disenos

FOR EACH ROW

EXECUTE FUNCTION
public.catalogo_controlar_publicacion();


