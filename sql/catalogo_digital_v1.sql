-- =========================================================
-- 1. TIPOS DE PRODUCTO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.catalogo_tipos_producto (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre TEXT NOT NULL UNIQUE,

    descripcion TEXT,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 2. CATEGORÍAS
-- =========================================================

CREATE TABLE IF NOT EXISTS public.catalogo_categorias (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nombre TEXT NOT NULL UNIQUE,

    descripcion TEXT,

    activo BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 3. DISEÑOS / PUBLICACIONES DEL CATÁLOGO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.catalogo_disenos (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Relación informativa con el ERP.
    -- Usamos el código de orden para no amarrarnos
    -- todavía al tipo exacto de ordenes.id.
    codigo_orden_origen TEXT,

    cliente_origen TEXT,

    arte_original_url TEXT,

    tipo_producto_id BIGINT
        REFERENCES public.catalogo_tipos_producto(id),

    categoria_id BIGINT
        REFERENCES public.catalogo_categorias(id),

    titulo TEXT NOT NULL,

    descripcion TEXT,

    colores TEXT[] DEFAULT '{}',

    etiquetas TEXT[] DEFAULT '{}',

    estado TEXT NOT NULL DEFAULT 'BORRADOR'
        CHECK (
            estado IN (
                'BORRADOR',
                'PUBLICADO',
                'OCULTO'
            )
        ),

    publicado BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    published_at TIMESTAMPTZ
);


-- =========================================================
-- 4. IMÁGENES DEL CATÁLOGO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.catalogo_imagenes (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    diseno_id BIGINT NOT NULL
        REFERENCES public.catalogo_disenos(id)
        ON DELETE CASCADE,

    nombre TEXT,

    storage_path TEXT NOT NULL,

    url_publica TEXT,

    orden INTEGER NOT NULL DEFAULT 1,

    es_portada BOOLEAN NOT NULL DEFAULT FALSE,

    ancho INTEGER,

    alto INTEGER,

    formato TEXT DEFAULT 'WEBP',

    peso_bytes BIGINT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- ÍNDICES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_catalogo_disenos_estado
ON public.catalogo_disenos(estado);


CREATE INDEX IF NOT EXISTS idx_catalogo_disenos_tipo
ON public.catalogo_disenos(tipo_producto_id);


CREATE INDEX IF NOT EXISTS idx_catalogo_disenos_categoria
ON public.catalogo_disenos(categoria_id);


CREATE INDEX IF NOT EXISTS idx_catalogo_disenos_orden
ON public.catalogo_disenos(codigo_orden_origen);


CREATE INDEX IF NOT EXISTS idx_catalogo_imagenes_diseno
ON public.catalogo_imagenes(diseno_id);


CREATE INDEX IF NOT EXISTS idx_catalogo_imagenes_orden
ON public.catalogo_imagenes(diseno_id, orden);


