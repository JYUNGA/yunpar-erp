-- =========================================================
-- 6. IMÁGENES DEL CATÁLOGO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.catalogo_imagenes (

    id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    diseno_id BIGINT
        NOT NULL
        REFERENCES public.catalogo_disenos(id)
        ON DELETE CASCADE,


    -- Nombre visible:
    -- Principal, Frente, Espalda, Detalle,
    -- Aplicación, Ambiente, etc.

    nombre TEXT
        NOT NULL
        DEFAULT 'Imagen',


    -- Ruta real dentro de Supabase Storage.
    --
    -- Ejemplo:
    -- diseno-25/01.webp

    storage_path TEXT
        NOT NULL
        UNIQUE,


    -- URL pública generada posteriormente.

    url_publica TEXT,


    -- Posición dentro del carrusel.

    orden INTEGER
        NOT NULL
        DEFAULT 1,


    -- Solo una imagen por diseño
    -- deberá ser portada.

    es_portada BOOLEAN
        NOT NULL
        DEFAULT FALSE,


    -- Información técnica.

    ancho INTEGER,

    alto INTEGER,

    formato TEXT
        NOT NULL
        DEFAULT 'WEBP',

    peso_bytes BIGINT,


    created_at TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),

    updated_at TIMESTAMPTZ
        NOT NULL
        DEFAULT NOW(),


    -- -----------------------------------------------------
    -- VALIDACIONES
    -- -----------------------------------------------------

    CONSTRAINT chk_catalogo_imagen_orden
        CHECK (
            orden >= 1
        ),

    CONSTRAINT chk_catalogo_imagen_ancho
        CHECK (
            ancho IS NULL
            OR ancho > 0
        ),

    CONSTRAINT chk_catalogo_imagen_alto
        CHECK (
            alto IS NULL
            OR alto > 0
        ),

    CONSTRAINT chk_catalogo_imagen_peso
        CHECK (
            peso_bytes IS NULL
            OR peso_bytes >= 0
        ),

    CONSTRAINT uq_catalogo_imagen_orden
        UNIQUE (
            diseno_id,
            orden
        )
);


