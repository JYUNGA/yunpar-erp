-- ============================================================
-- NORMALIZAR ESTADOS DE ÓRDENES (YUNPAR)
-- Ejecutar en Supabase → SQL Editor.
-- 1) Diagnóstico: ver los estados distintos actuales.
-- 2) UPDATE: normaliza todas las variantes al valor canónico.
-- ============================================================

-- 1. DIAGNÓSTICO (ejecutar primero para ver qué variantes existen)
SELECT estado, COUNT(*) AS cantidad
FROM public.ordenes
GROUP BY estado
ORDER BY cantidad DESC;

-- 2. NORMALIZACIÓN (estandariza las variantes conocidas; el resto se pasa a MAYÚSCULAS)
UPDATE public.ordenes
SET estado = CASE UPPER(TRIM(COALESCE(estado, '')))
    WHEN 'PENDIENTE DISEÑO' THEN 'PENDIENTE DISEÑO'
    WHEN 'PENDIENTE DISENO' THEN 'PENDIENTE DISEÑO'
    WHEN 'PENDIENTES DISEÑO' THEN 'PENDIENTE DISEÑO'
    WHEN 'PENDIENTE' THEN 'PENDIENTE DISEÑO'
    WHEN 'EN DISEÑO' THEN 'EN DISEÑO'
    WHEN 'EN DISENO' THEN 'EN DISEÑO'
    WHEN 'DISEÑO' THEN 'EN DISEÑO'
    WHEN 'DISENO' THEN 'EN DISEÑO'
    WHEN 'LISTO PARA IMPRESIÓN' THEN 'LISTO PARA IMPRESIÓN'
    WHEN 'LISTO PARA IMPRESION' THEN 'LISTO PARA IMPRESIÓN'
    WHEN 'LISTO IMPRESIÓN' THEN 'LISTO PARA IMPRESIÓN'
    WHEN 'LISTO IMPRESION' THEN 'LISTO PARA IMPRESIÓN'
    WHEN 'EN IMPRESIÓN' THEN 'EN IMPRESIÓN'
    WHEN 'EN IMPRESION' THEN 'EN IMPRESIÓN'
    WHEN 'IMPRESIÓN' THEN 'EN IMPRESIÓN'
    WHEN 'IMPRESION' THEN 'EN IMPRESIÓN'
    WHEN 'EN SUBLIMACIÓN' THEN 'EN SUBLIMACIÓN'
    WHEN 'EN SUBLIMACION' THEN 'EN SUBLIMACIÓN'
    WHEN 'SUBLIMACIÓN' THEN 'EN SUBLIMACIÓN'
    WHEN 'SUBLIMACION' THEN 'EN SUBLIMACIÓN'
    WHEN 'EN CONFECCIÓN' THEN 'EN CONFECCIÓN'
    WHEN 'EN CONFECCION' THEN 'EN CONFECCIÓN'
    WHEN 'CONFECCIÓN' THEN 'EN CONFECCIÓN'
    WHEN 'CONFECCION' THEN 'EN CONFECCIÓN'
    WHEN 'COSTURA' THEN 'EN CONFECCIÓN'
    WHEN 'LISTA PARA ENTREGA' THEN 'LISTA PARA ENTREGA'
    WHEN 'LISTO PARA ENTREGA' THEN 'LISTA PARA ENTREGA'
    WHEN 'LISTO ENTREGA' THEN 'LISTA PARA ENTREGA'
    WHEN 'ENTREGADO' THEN 'ENTREGADO'
    WHEN 'ENTREGADA' THEN 'ENTREGADO'
    WHEN 'ANULADO' THEN 'ANULADO'
    WHEN 'ANULADA' THEN 'ANULADO'
    WHEN 'CANCELADO' THEN 'ANULADO'
    WHEN 'CANCELADA' THEN 'ANULADO'
    ELSE UPPER(TRIM(COALESCE(estado, '')))
END
WHERE estado IS NOT NULL;
