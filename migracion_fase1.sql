-- 5. (Opcional, Fase 1.5) Contador atómico de códigos.
--    Elimina la "race condition" en la generación de códigos (VD-, M, COT-).
--    La app debería llamar a una RPC en lugar de contar filas.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.contadores_codigo (
    prefijo text PRIMARY KEY,
    valor integer NOT NULL DEFAULT 0
);

CREATE OR REPLACE FUNCTION public.siguiente_codigo(p_prefijo text)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_valor integer;
BEGIN
    INSERT INTO public.contadores_codigo (prefijo, valor)
    VALUES (p_prefijo, 1)
    ON CONFLICT (prefijo)
    DO UPDATE SET valor = public.contadores_codigo.valor + 1
    RETURNING valor INTO v_valor;
    RETURN v_valor;
END $$;

