-- ------------------------------------------------------------
-- 7. RPC transaccional para registrar un pago/abono.
--    Reemplaza el patrón "insert pago + recalcular saldo" por una
--    sola operación atómica (evita saldos inconsistentes).
--    La app puede llamarla con supabase.rpc("registrar_pago", {...}).
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.registrar_pago(
    p_orden_id integer,
    p_cliente_id integer,
    p_monto numeric,
    p_metodo text,
    p_banco text DEFAULT NULL,
    p_numero_referencia text DEFAULT NULL,
    p_registrado_por integer DEFAULT NULL
)
RETURNS numeric
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_total numeric;
    v_suma numeric;
    v_saldo numeric;
BEGIN
    IF p_monto IS NULL OR p_monto <= 0 THEN
        RAISE EXCEPTION 'El monto debe ser mayor a 0';
    END IF;

    INSERT INTO public.pagos (
        orden_id, cliente_id, monto, metodo_pago, banco_destino,
        numero_referencia, fecha_pago, registrado_por_id, created_at
    ) VALUES (
        p_orden_id, p_cliente_id, p_monto, p_metodo, p_banco,
        p_numero_referencia, CURRENT_DATE, p_registrado_por, now()
    );

    SELECT COALESCE(total_estimado, 0) INTO v_total
      FROM public.ordenes WHERE id = p_orden_id;

    SELECT COALESCE(SUM(monto), 0) INTO v_suma
      FROM public.pagos
     WHERE orden_id = p_orden_id AND COALESCE(anulado, false) = false;

    v_saldo := GREATEST(v_total - v_suma, 0);

    UPDATE public.ordenes
       SET saldo_pendiente = v_saldo
     WHERE id = p_orden_id;

    RETURN v_saldo;
END $$;
