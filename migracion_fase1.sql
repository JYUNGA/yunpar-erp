-- 1. Tabla de asignaciones de taller (requerida por control_taller.py)
--    Antes, el botón "Confirmar Asignación" mostraba éxito sin guardar.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.asignaciones_taller (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id integer NOT NULL REFERENCES public.ordenes(id) ON DELETE CASCADE,
    cortador_id integer REFERENCES public.rh_empleados(id),
    costurera_id integer REFERENCES public.rh_empleados(id),
    asignado_por integer REFERENCES public.usuarios(id),
    prendas integer NOT NULL DEFAULT 0,
    created_at timestamp without time zone DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_asignaciones_taller_orden
    ON public.asignaciones_taller (orden_id);

-- ------------------------------------------------------------
-- 2. Anti doble liquidación de nómina.
--    Impide pagar dos veces el mismo empleado/mes.
--    IMPORTANTE: verifica el nombre real de la columna de mes en tu tabla
--    rh_liquidaciones. El código Python inserta "mes_anio". Si tu columna
--    se llama "mes", cambia la línea de abajo en consecuencia.
-- ------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'rh_liquidaciones'
          AND column_name = 'mes_anio'
    ) THEN
        ALTER TABLE public.rh_liquidaciones
            DROP CONSTRAINT IF EXISTS rh_liquidaciones_empleado_mes_key;
        ALTER TABLE public.rh_liquidaciones
            ADD CONSTRAINT rh_liquidaciones_empleado_mes_key
            UNIQUE (empleado_id, mes_anio);
    ELSIF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'rh_liquidaciones'
          AND column_name = 'mes'
    ) THEN
        ALTER TABLE public.rh_liquidaciones
            DROP CONSTRAINT IF EXISTS rh_liquidaciones_empleado_mes_key;
        ALTER TABLE public.rh_liquidaciones
            ADD CONSTRAINT rh_liquidaciones_empleado_mes_key
            UNIQUE (empleado_id, mes);
    END IF;
END $$;

